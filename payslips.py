
from io import BytesIO

import pandas as pd
import streamlit as st
from database import get_connection


def get_payroll_for_payslips():
    with get_connection() as conn:
        return pd.read_sql_query(
            """
            SELECT
                p.payroll_id,
                p.employee_id,
                e.full_name,
                e.department,
                e.designation,
                e.email,
                e.joining_date,
                p.pay_month,
                p.working_days,
                p.payable_days,
                p.gross_salary,
                p.total_deductions,
                p.net_salary,
                p.payment_status
            FROM payroll p
            JOIN employees e
                ON p.employee_id = e.employee_id
            ORDER BY p.pay_month DESC, e.full_name
            """,
            conn
        )


def create_payslip_pdf(row):
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet
        from reportlab.lib.units import mm
        from reportlab.platypus import (
            SimpleDocTemplate,
            Paragraph,
            Spacer,
            Table,
            TableStyle
        )
    except ImportError as error:
        raise ImportError(
            "PDF support is missing. Install reportlab using "
            "'python3 -m pip install reportlab'."
        ) from error

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=20 * mm,
        bottomMargin=20 * mm
    )

    styles = getSampleStyleSheet()
    content = []

    content.append(Paragraph("EMPLOYEE PAYSLIP", styles["Title"]))
    content.append(Spacer(1, 12))

    employee_info = [
        ["Employee Name", str(row["full_name"])],
        ["Employee ID", str(row["employee_id"])],
        ["Department", str(row["department"] or "-")],
        ["Designation", str(row["designation"] or "-")],
        ["Email", str(row["email"] or "-")],
        ["Joining Date", str(row["joining_date"] or "-")],
        ["Salary Month", str(row["pay_month"])],
        ["Working Days", str(row["working_days"])],
        ["Payable Days", str(row["payable_days"])],
        ["Payment Status", str(row["payment_status"])]
    ]

    info_table = Table(
        employee_info,
        colWidths=[50 * mm, 105 * mm]
    )
    info_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.whitesmoke),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("PADDING", (0, 0), (-1, -1), 8)
    ]))

    content.append(info_table)
    content.append(Spacer(1, 20))

    salary_data = [
        ["Salary Component", "Amount (INR)"],
        ["Gross Salary", f"Rs. {row['gross_salary']:,.2f}"],
        ["Total Deductions", f"Rs. {row['total_deductions']:,.2f}"],
        ["Net Salary", f"Rs. {row['net_salary']:,.2f}"]
    ]

    salary_table = Table(
        salary_data,
        colWidths=[90 * mm, 65 * mm]
    )
    salary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#4338CA")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("ALIGN", (1, 1), (1, -1), "RIGHT"),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
        ("BACKGROUND", (0, -1), (-1, -1), colors.whitesmoke),
        ("PADDING", (0, 0), (-1, -1), 9)
    ]))

    content.append(salary_table)
    content.append(Spacer(1, 24))
    content.append(Paragraph(
        "This payslip was generated by the Employee Payroll & HR "
        "Management System.",
        styles["Normal"]
    ))

    document.build(content)
    buffer.seek(0)
    return buffer.getvalue()


def render_payslips():
    st.title("Payslips")
    st.caption("View payroll details and download salary slips as PDFs.")

    records = get_payroll_for_payslips()

    if records.empty:
        st.info("No payroll records are available yet. Generate payroll first.")
        return

    records["label"] = records.apply(
        lambda row: (
            f"{row['full_name']} | {row['pay_month']} | "
            f"Payroll ID: {row['payroll_id']}"
        ),
        axis=1
    )

    selected_label = st.selectbox(
        "Select Employee Payslip",
        records["label"].tolist()
    )

    row = records.loc[
        records["label"] == selected_label
    ].iloc[0]

    st.subheader(f"Payslip — {row['pay_month']}")
    st.write(f"**Employee:** {row['full_name']}")
    st.write(f"**Employee ID:** {row['employee_id']}")
    st.write(f"**Department:** {row['department'] or '-'}")
    st.write(f"**Designation:** {row['designation'] or '-'}")
    st.write(f"**Payment Status:** {row['payment_status']}")

    col1, col2, col3 = st.columns(3)

    col1.metric("Gross Salary", f"₹{row['gross_salary']:,.2f}")
    col2.metric("Deductions", f"₹{row['total_deductions']:,.2f}")
    col3.metric("Net Salary", f"₹{row['net_salary']:,.2f}")

    st.divider()

    salary_details = pd.DataFrame({
        "Component": [
            "Gross Salary",
            "Total Deductions",
            "Net Salary"
        ],
        "Amount (₹)": [
            row["gross_salary"],
            row["total_deductions"],
            row["net_salary"]
        ]
    })

    st.dataframe(salary_details, hide_index=True, use_container_width=True)

    try:
        pdf_bytes = create_payslip_pdf(row)

        st.download_button(
            label="Download Payslip PDF",
            data=pdf_bytes,
            file_name=(
                f"Payslip_{row['employee_id']}_{row['pay_month']}.pdf"
            ),
            mime="application/pdf"
        )

    except ImportError as error:
        st.warning(str(error))
